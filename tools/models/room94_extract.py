#!/usr/bin/env python3
"""Map 94's art, per column, from a flat focus dump (KOL_FOCUS_DUMP with
KOL_EDGE_BLUR=1, the perspective off, unlit): writes room94_art.py.

    tools/models/room94_extract.py <dump prefix>    (prefix.rgb / .layers / .info)

The dump used: Thor state 0228 (a dialogue on the cliff, camera at rest),
384 x 216, KX 208, KY 124. Rock is r > b (brown top, yellow face); the clouds
and sky are b >= r. Both are BG0 (the cliff's top outline BG1). Two rocks:
the main cliff and, at the lower right, a lower spire, split by a crack of
cloud a pixel wide (4-connected components, seeded inside each). Sprite and
interface pixels (layers 2-4) are unknown: inside a rock they are rock; a
column whose first pixel is unknown (the girl over the far edge) takes its
top row from its neighbours.

For each rock and column, the runs of rock pixels (first row, last row), and
for each column the first row of the rock's lit vertical face (the yellow
palette; the top is the brown one): three of four pixels from that row on.
"""
import os
import sys

FACE = {(198, 165, 90), (231, 189, 74), (247, 222, 123), (156, 132, 74), (107, 90, 41), (247, 247, 156),
        (148, 115, 66)}


def main(prefix):
    info = open(prefix + ".info").read().split("\n")[0].split()
    p = {info[i]: int(info[i + 1]) for i in range(0, len(info) - 1, 2)}
    W, H = p["w"], p["h"]
    KX, KY = p["kx"] + p["ox"], p["ky"] + p["oy"]
    rgb = open(prefix + ".rgb", "rb").read()
    lay = open(prefix + ".layers", "rb").read()

    def col(x, y):
        i = (y * W + x) * 3
        return rgb[i], rgb[i + 1], rgb[i + 2]

    def kind(x, y):   # 1 rock, 0 cloud, 2 unknown
        l = lay[y * W + x] & 15
        if l in (2, 3, 4):
            return 2
        if l == 1:     # the top's dark outline (33,49,66): the cliff's, b > r
            return 1
        r, g, b = col(x, y)
        return 1 if r > b else 0

    K = [[kind(x, y) for x in range(W)] for y in range(H)]

    def comp(seed):
        seen = set([seed])
        st = [seed]
        while st:
            x, y = st.pop()
            for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
                if 0 <= nx < W and 0 <= ny < H and (nx, ny) not in seen and K[ny][nx] != 0 and ny >= 95:
                    seen.add((nx, ny))
                    st.append((nx, ny))
        return seen

    main_c = comp((100, 200))
    spire_c = comp((250, 200))
    assert not (main_c & spire_c), "the rocks touch"

    def runs(cset):
        out = {}
        for x in range(W):
            rs = []
            y = 0
            while y < H:
                if (x, y) in cset:
                    y0 = y
                    while y < H and (x, y) in cset:
                        y += 1
                    rs.append([y0, y - 1])
                else:
                    y += 1
            # a run that starts on an unknown pixel: its top from the neighbours
            if rs:
                out[x] = rs
        # trim unknown pixels off the top of each column's first run
        unknown_top = [x for x in out if K[out[x][0][0]][x] == 2]
        for x in unknown_top:
            y = out[x][0][0]
            while K[y][x] == 2:
                y += 1
            out[x][0][0] = y   # provisional: the first known pixel
        known = sorted(x for x in out if x not in unknown_top)
        for x in unknown_top:
            l = max([k for k in known if k < x], default=None)
            r = min([k for k in known if k > x], default=None)
            if l is None or r is None:
                continue
            t = (x - l) / (r - l)
            out[x][0][0] = min(out[x][0][0], int(round(out[l][0][0] + (out[r][0][0] - out[l][0][0]) * t)))
        return out

    def first_face(x):
        for y in range(100, H - 3):
            if sum(1 for k in range(4) if lay[(y + k) * W + x] & 15 in (0, 1) and col(x, y + k) in FACE) >= 3:
                return y
        return None

    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "room94_art.py"), "w") as o:
        o.write("# Generated by tools/models/room94_extract.py from %s: do not edit.\n" % os.path.basename(prefix))
        o.write("# Map 94's art per column of the flat frame (W %d, H %d, KX %d, KY %d).\n" % (W, H, KX, KY))
        o.write("W, H, KX, KY = %d, %d, %d, %d\n" % (W, H, KX, KY))
        for name, cset in (("MAIN", main_c), ("SPIRE", spire_c)):
            r = runs(cset)
            o.write("%s = {\n" % name)
            for x in sorted(r):
                o.write("    %d: %r,\n" % (x, [tuple(a) for a in r[x]]))
            o.write("}\n")
        o.write("FIRST_FACE = {\n")
        for x in range(W):
            f = first_face(x)
            if f is not None:
                o.write("    %d: %d,\n" % (x, f))
        o.write("}\n")


if __name__ == "__main__":
    main(sys.argv[1])
