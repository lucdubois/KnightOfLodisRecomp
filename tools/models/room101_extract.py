#!/usr/bin/env python3
"""The user's painting of map 101's walls -> tools/models/room101_runs.py,
each face's painted pixels as column runs (x, top row, bottom row) in the
384x216 view's columns and rows from its window's row 36 (README "The
arcade, modelled"). shots/castle_room/HS_drawn_480.png: the 480x270 view at
4x (its column 48 the 384 view's 0, its row 36 the 384 window's 36), the
first painting (HS_drawn.png, 384x180 from row 36) pasted in and the band
above it painted on the Thor's width.

Colours: green the floor; red (255,31,0) the window wall's alcoves (+X),
orange (255,73,0) its arcade and the corner pillar's +X face, magenta the
+Z faces (the back wall's arcade, the pillars' sides, the corner's), the
two other oranges the back wall's pillars' +X sides.

    tools/models/room101_extract.py DRAWN.png [X0 Y0]   (the 384 view's 0, 36 in DRAWN's 1x pixels: 48 36 for the 480 canvas)
"""
import os
import sys
from PIL import Image

COL = {(255, 0, 255): 'M', (42, 255, 0): 'G', (255, 73, 0): 'O', (255, 31, 0): 'R',
       (255, 99, 0): 'P', (255, 125, 0): 'Q'}


def main(path, ox=0, oy=0):
    im = Image.open(path).convert('RGB')
    p = im.load()
    W, H = im.width // 4, im.height // 4
    lab = [[COL.get(p[x * 4 + 2, y * 4 + 2], '.') for x in range(W)] for y in range(H)]
    seen = set()
    faces = []
    for y in range(H):
        for x in range(W):
            ch = lab[y][x]
            if ch in '.G' or (x, y) in seen:
                continue
            st, px = [(x, y)], []
            seen.add((x, y))
            while st:
                a, b = st.pop()
                px.append((a, b))
                for q in ((a + 1, b), (a - 1, b), (a, b + 1), (a, b - 1)):
                    if 0 <= q[0] < W and 0 <= q[1] < H and q not in seen and lab[q[1]][q[0]] == ch:
                        seen.add(q)
                        st.append(q)
            if len(px) < 20:
                continue
            runs = []
            cols = {}
            for a, b in px:
                cols.setdefault(a, []).append(b)
            for a in sorted(cols):
                ys = sorted(cols[a])
                s = ys[0]
                for i in range(1, len(ys) + 1):
                    if i == len(ys) or ys[i] != ys[i - 1] + 1:
                        runs.append((a, s, ys[i - 1]))
                        if i < len(ys):
                            s = ys[i]
            runs = [(a - ox, t - oy, b - oy) for a, t, b in runs]
            faces.append((ch, min(c[0] for c in px) - ox, runs))
    out = os.path.join(os.path.dirname(__file__), 'room101_runs.py')
    with open(out, 'w') as o:
        o.write('# Generated by room101_extract.py from the user\'s painting: (colour, first column, runs).\n')
        o.write('FACES = [\n')
        for ch, x0, runs in faces:
            o.write('    (%r, %d, %r),\n' % (ch, x0, runs))
        o.write(']\n')
    print('%d faces -> %s' % (len(faces), out))


if __name__ == '__main__':
    main(sys.argv[1], *(int(v) for v in sys.argv[2:4]))
