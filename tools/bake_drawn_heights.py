#!/usr/bin/env python3
"""Bake a drawn_heights.cfg (the Thor's editor file) into the build.

    adb exec-out "run-as com.koldecomp.game cat files/drawn_heights.cfg" > /tmp/dh.cfg
    tools/bake_drawn_heights.py /tmp/dh.cfg

Writes src/kol_drawn_baked.inc: the file's lines (heights, types, roofs, boxes, suns, water,
indoor tags; no
comments), sorted by map, as the text kol_tile_edit loads when the device
has no drawn_heights.cfg of its own.
"""
import os
import sys


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    kinds = {"h": [], "type": [], "roof": [], "box": [], "sun": [], "water": [], "indoor": []}
    for raw in open(sys.argv[1]):
        line = " ".join(raw.split())
        if not line or line.startswith("#"):
            continue
        f = line.split()
        kind = f[0] if f[0] in ("type", "roof", "box", "sun", "water", "indoor") else "h"
        nums = f[1:] if kind != "h" else f
        kinds[kind].append((int(nums[0]), line))
    out = os.path.join(os.path.dirname(__file__), "..", "src", "kol_drawn_baked.inc")
    with open(out, "w") as o:
        o.write("// Generated by tools/bake_drawn_heights.py from the Thor's drawn_heights.cfg.\n")
        o.write("// Do not edit: edit on the device (Debug > Tile Info) and bake again.\n")
        o.write('R"cfg(')
        for kind in ("h", "type", "roof", "box", "sun", "water", "indoor"):
            # A stable sort: lines of a map keep the file's order.
            for _, line in sorted(kinds[kind], key=lambda t: t[0]):
                o.write(line + "\n")
        o.write(')cfg"\n')
    print("%d heights, %d types, %d roofs, %d boxes, %d suns, %d water, %d indoor -> %s" % (
        len(kinds["h"]), len(kinds["type"]), len(kinds["roof"]), len(kinds["box"]), len(kinds["sun"]),
        len(kinds["water"]), len(kinds["indoor"]),
        os.path.normpath(out)))


if __name__ == "__main__":
    main()
