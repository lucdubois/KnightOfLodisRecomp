#!/usr/bin/env python3
"""Generate the HD instruments mapping the game loads from kol_hd_map.json.

    tools/hd_audio/gen_map.py

Writes src/kol_hd_map.inc: the JSON's two tables as C++ arrays, kHdSamples
(which instrument plays each music sample) and kHdPsg (what plays each PSG
channel, per song), with (bank, program) left for kol_hd_audio.cpp to resolve
against the bank it loads. The row types are kol_hd_audio.cpp's.
"""
import json
import os
import sys


def num(v):
    """An int field: a JSON number, or a "0x..." string."""
    return int(v, 0) if isinstance(v, str) else int(v)


def flt(v):
    return repr(float(v)) + "f"


def note(row):
    n = row.get("note")
    return "   // " + " ".join(n.split()) if n else ""


def adr(v):
    """A ROM address as the source writes one: the USA ROM's, in usa()
    (src/kol_region.h), so another region's build translates it. 0 = none."""
    return "usa(0x%08Xu)" % v if v else "0x00000000u"


def main():
    if len(sys.argv) != 1:
        sys.exit(__doc__)
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "kol_hd_map.json")) as f:
        m = json.load(f)
    out = os.path.join(here, "..", "..", "src", "kol_hd_map.inc")
    with open(out, "w") as o:
        o.write("// Generated by tools/hd_audio/gen_map.py from tools/hd_audio/kol_hd_map.json.\n")
        o.write("// Do not edit: edit the JSON and generate again.\n")
        o.write("// {wav, bank, prog, offset, gain_db, kit_key, roll_hz, accent, song (0: every song),\n"
                "//  intro_s, intro_db, intro_ramp}\n")
        o.write("constexpr HdSampleRow kHdSamples[] = {\n")
        for r in m["samples"]:
            o.write("    {%s, %d, %d, %s, %s, %d, %s, %s, %s, %s, %s, %d},%s\n" % (
                adr(num(r["wav"])), num(r["bank"]), num(r["prog"]), flt(r.get("offset", 0)),
                flt(r.get("gain_db", 0)), num(r.get("kit_key", -1)), flt(r.get("roll_hz", 0)),
                flt(r.get("accent", 0.7)), adr(num(r.get("song", 0))), flt(r.get("intro_s", 0)),
                flt(r.get("intro_db", 0)), 1 if r.get("intro_ramp") else 0, note(r)))
        o.write("};\n")
        o.write("// {song, channel, bank, prog, transpose, gain_db}\n")
        o.write("constexpr HdPsgRow kHdPsg[] = {\n")
        for r in m["psg"]:
            o.write("    {%s, %d, %d, %d, %s, %s},%s\n" % (
                adr(num(r["song"])), num(r["channel"]), num(r["bank"]), num(r["prog"]),
                flt(r.get("transpose", 0)), flt(r.get("gain_db", 0)), note(r)))
        o.write("};\n")
    print("%d samples, %d psg -> %s" % (len(m["samples"]), len(m["psg"]), os.path.normpath(out)))


if __name__ == "__main__":
    main()
